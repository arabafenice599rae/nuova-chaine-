#!/usr/bin/env python3
"""Generates THIRD_PARTY_NOTICES from Cargo.lock: the crates linked into the
`centrifuga` binary on Linux (no dev/build dependencies, no proc-macros), with
their license and the license/notice files each crate ships.

Usage: scripts/third-party-notices.py > THIRD_PARTY_NOTICES
CI regenerates it and fails if it differs from the committed file.
"""
import hashlib
import json
import os
import subprocess
import sys

meta = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", "x86_64-unknown-linux-gnu"]))
pkgs = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
root = meta["resolve"]["root"]

linked, stack = set(), [root]
while stack:
    i = stack.pop()
    if i in linked:
        continue
    linked.add(i)
    for d in nodes[i]["deps"]:
        if any(k["kind"] is None for k in d["dep_kinds"]):
            stack.append(d["pkg"])
linked.discard(root)
# Only third-party crates: path crates (programs/timelock) are part of this repository.
linked = [i for i in linked if pkgs[i]["source"] and not any("proc-macro" in t["kind"] for t in pkgs[i]["targets"])]
linked.sort(key=lambda i: (pkgs[i]["name"], pkgs[i]["version"]))

PREFIXES = ("license", "licence", "copying", "notice", "copyright", "unlicense")
texts = {}  # sha -> (text, [crate])
missing = []
for i in linked:
    p = pkgs[i]
    d = os.path.dirname(p["manifest_path"])
    found = False
    for f in sorted(os.listdir(d)):
        path = os.path.join(d, f)
        if os.path.isfile(path) and f.lower().startswith(PREFIXES):
            t = open(path, encoding="utf-8", errors="replace").read().strip()
            h = hashlib.sha256(t.encode()).hexdigest()
            texts.setdefault(h, (t, []))[1].append(f"{p['name']} {p['version']}")
            found = True
    if not found:
        missing.append(p)

# Standard Apache-2.0 text (the most shared one): it also covers the Apache-2.0
# crates that ship no license file.
apache = max((h for h, (t, _) in texts.items() if "Apache License" in t[:200] and "Version 2.0" in t[:300]),
             key=lambda h: len(texts[h][1]), default=None)
still = []
for p in missing:
    if apache and "Apache-2.0" in (p.get("license") or ""):
        texts[apache][1].append(f"{p['name']} {p['version']} (no license file shipped)")
    else:
        still.append(p)
missing = still

out = sys.stdout
out.write("THIRD-PARTY NOTICES for the centrifuga binary\n")
out.write("Generated by scripts/third-party-notices.py from Cargo.lock. Do not edit by hand.\n\n")
out.write("centrifuga itself is MIT licensed (see LICENSE). It links the crates below.\n")
out.write("Where a crate offers a choice (\"A OR B\"), any of the listed licenses applies.\n\n")
out.write("== Crates ==\n\n")
for i in linked:
    p = pkgs[i]
    out.write(f"{p['name']} {p['version']}  {p.get('license') or p.get('license_file') or 'UNKNOWN'}  {p.get('repository') or ''}\n".rstrip() + "\n")
out.write("\n== License and notice files shipped by the crates ==\n")
for h, (t, crates) in sorted(texts.items(), key=lambda kv: kv[1][1][0]):
    out.write("\n" + "-" * 78 + "\n")
    out.write("Applies to: " + ", ".join(crates) + "\n\n")
    out.write(t + "\n")
if missing:
    out.write("\n" + "-" * 78 + "\n")
    out.write("Crates that ship no license file (the standard SPDX text of the listed license applies):\n")
    for p in missing:
        authors = ", ".join(p.get("authors") or []) or "see repository"
        out.write(f"  {p['name']} {p['version']}  {p.get('license')}  Copyright: {authors}\n")
